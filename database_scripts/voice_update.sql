-- ===== المتابعة =====
CREATE TABLE IF NOT EXISTS public.follows (
  follower uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  followee uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (follower, followee),
  CHECK (follower <> followee)
);
ALTER TABLE public.follows ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS follows_read ON public.follows;
CREATE POLICY follows_read ON public.follows FOR SELECT TO authenticated USING (true);
GRANT SELECT ON public.follows TO authenticated;

-- ===== الرسائل الخاصة =====
CREATE TABLE IF NOT EXISTS public.dms (
  id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  sender_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  receiver_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz,
  CHECK (sender_id <> receiver_id)
);
CREATE INDEX IF NOT EXISTS dms_pair_idx ON public.dms (sender_id, receiver_id, id DESC);
CREATE INDEX IF NOT EXISTS dms_recv_idx ON public.dms (receiver_id, read_at);
ALTER TABLE public.dms ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS dms_read ON public.dms;
DROP POLICY IF EXISTS dms_insert ON public.dms;
CREATE POLICY dms_read ON public.dms FOR SELECT TO authenticated USING (sender_id = auth.uid() OR receiver_id = auth.uid());
CREATE POLICY dms_insert ON public.dms FOR INSERT TO authenticated WITH CHECK (sender_id = auth.uid());
GRANT SELECT, INSERT ON public.dms TO authenticated;

-- ===== مقاعد المايك (0 = مقعد المضيف، 1..8 للمتحدثين) =====
CREATE TABLE IF NOT EXISTS public.room_seats (
  room_id uuid NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
  seat_no smallint NOT NULL CHECK (seat_no BETWEEN 0 AND 8),
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  PRIMARY KEY (room_id, seat_no),
  UNIQUE (room_id, user_id)
);
ALTER TABLE public.room_seats ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS seats_read ON public.room_seats;
CREATE POLICY seats_read ON public.room_seats FOR SELECT TO authenticated USING (true);
GRANT SELECT ON public.room_seats TO authenticated;

-- ===== دوال =====
CREATE OR REPLACE FUNCTION public.take_seat(p_room uuid, p_seat int)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE r public.rooms%ROWTYPE;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;
  SELECT * INTO r FROM rooms WHERE id = p_room AND is_live;
  IF NOT FOUND THEN RAISE EXCEPTION 'room not live'; END IF;
  IF p_seat < 0 OR p_seat > 8 THEN RAISE EXCEPTION 'bad seat'; END IF;
  IF p_seat = 0 AND r.host_id <> auth.uid() THEN RAISE EXCEPTION 'host only'; END IF;
  DELETE FROM room_seats WHERE room_id = p_room AND user_id = auth.uid();
  INSERT INTO room_seats(room_id, seat_no, user_id) VALUES (p_room, p_seat, auth.uid());
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'seat taken';
END $$;

CREATE OR REPLACE FUNCTION public.leave_seat(p_room uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  DELETE FROM room_seats WHERE room_id = p_room AND user_id = auth.uid();
$$;

CREATE OR REPLACE FUNCTION public.kick_seat(p_room uuid, p_seat int)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  DELETE FROM room_seats s USING rooms r
  WHERE s.room_id = p_room AND s.seat_no = p_seat AND s.seat_no <> 0
    AND r.id = s.room_id AND r.host_id = auth.uid();
$$;

CREATE OR REPLACE FUNCTION public.leave_room(p_room uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  DELETE FROM room_seats WHERE room_id = p_room AND user_id = auth.uid();
  DELETE FROM room_members WHERE room_id = p_room AND user_id = auth.uid();
$$;

CREATE OR REPLACE FUNCTION public.room_heartbeat(p_room uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE live boolean;
BEGIN
  IF auth.uid() IS NULL THEN RAISE EXCEPTION 'not authenticated'; END IF;
  SELECT is_live INTO live FROM rooms WHERE id = p_room;
  IF live IS NOT TRUE THEN RETURN false; END IF;
  INSERT INTO room_members(room_id, user_id, last_seen) VALUES (p_room, auth.uid(), now())
  ON CONFLICT (room_id, user_id) DO UPDATE SET last_seen = now();
  DELETE FROM room_seats s WHERE s.room_id = p_room AND NOT EXISTS (
    SELECT 1 FROM room_members m WHERE m.room_id = s.room_id AND m.user_id = s.user_id
      AND m.last_seen > now() - interval '45 seconds');
  RETURN true;
END $$;

DROP FUNCTION IF EXISTS public.list_rooms();
CREATE FUNCTION public.list_rooms()
RETURNS TABLE(id uuid, title text, topic text, host_id uuid, host_name text, host_avatar text, listeners int, seated int, created_at timestamptz)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT r.id, r.title, r.topic, r.host_id, p.name, p.avatar_url,
         (SELECT count(*)::int FROM room_members m WHERE m.room_id = r.id AND m.last_seen > now() - interval '45 seconds'),
         (SELECT count(*)::int FROM room_seats s WHERE s.room_id = r.id),
         r.created_at
  FROM rooms r JOIN profiles p ON p.id = r.host_id
  WHERE r.is_live
    AND ( r.created_at > now() - interval '3 minutes'
          OR EXISTS (SELECT 1 FROM room_members m WHERE m.room_id = r.id AND m.last_seen > now() - interval '45 seconds') )
  ORDER BY 7 DESC, r.created_at DESC
  LIMIT 100;
$$;

CREATE OR REPLACE FUNCTION public.search_profiles(q text)
RETURNS TABLE(id uuid, name text, username text, num bigint, avatar_url text, bio text, followers int, is_following boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT p.id, p.name, p.username, p.num, p.avatar_url, p.bio,
         (SELECT count(*)::int FROM follows f WHERE f.followee = p.id),
         EXISTS (SELECT 1 FROM follows f WHERE f.follower = auth.uid() AND f.followee = p.id)
  FROM profiles p
  WHERE p.id <> auth.uid()
    AND ( btrim(q) = '' OR p.name ILIKE '%' || btrim(q) || '%'
          OR p.username ILIKE '%' || btrim(q) || '%' OR p.num::text = btrim(q) )
  ORDER BY p.created_at DESC
  LIMIT 30;
$$;

CREATE OR REPLACE FUNCTION public.get_profile(p_id uuid)
RETURNS TABLE(id uuid, name text, username text, num bigint, avatar_url text, bio text, followers int, following int, is_following boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT p.id, p.name, p.username, p.num, p.avatar_url, p.bio,
         (SELECT count(*)::int FROM follows f WHERE f.followee = p.id),
         (SELECT count(*)::int FROM follows f WHERE f.follower = p.id),
         EXISTS (SELECT 1 FROM follows f WHERE f.follower = auth.uid() AND f.followee = p.id)
  FROM profiles p WHERE p.id = p_id;
$$;

CREATE OR REPLACE FUNCTION public.follow_user(p_id uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  INSERT INTO follows(follower, followee) SELECT auth.uid(), p_id WHERE auth.uid() <> p_id
  ON CONFLICT DO NOTHING;
$$;

CREATE OR REPLACE FUNCTION public.unfollow_user(p_id uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  DELETE FROM follows WHERE follower = auth.uid() AND followee = p_id;
$$;

CREATE OR REPLACE FUNCTION public.my_conversations()
RETURNS TABLE(peer_id uuid, peer_name text, peer_username text, peer_avatar text, last_body text, last_at timestamptz, unread int)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  WITH m AS (
    SELECT CASE WHEN sender_id = auth.uid() THEN receiver_id ELSE sender_id END AS peer, body, created_at
    FROM dms WHERE sender_id = auth.uid() OR receiver_id = auth.uid()
  ), lm AS (
    SELECT DISTINCT ON (peer) peer, body, created_at FROM m ORDER BY peer, created_at DESC
  ), un AS (
    SELECT sender_id AS peer, count(*)::int AS c FROM dms WHERE receiver_id = auth.uid() AND read_at IS NULL GROUP BY 1
  )
  SELECT p.id, p.name, p.username, p.avatar_url, lm.body, lm.created_at, COALESCE(un.c, 0)
  FROM lm JOIN profiles p ON p.id = lm.peer LEFT JOIN un ON un.peer = lm.peer
  ORDER BY lm.created_at DESC LIMIT 100;
$$;

CREATE OR REPLACE FUNCTION public.mark_read(p_peer uuid)
RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public AS $$
  UPDATE dms SET read_at = now() WHERE receiver_id = auth.uid() AND sender_id = p_peer AND read_at IS NULL;
$$;

