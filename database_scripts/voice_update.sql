CREATE OR REPLACE FUNCTION public.profiles_default_username() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.username IS NULL THEN NEW.username := 'user' || NEW.num; END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS profiles_default_username ON public.profiles;
CREATE TRIGGER profiles_default_username BEFORE INSERT ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.profiles_default_username();

-- المستخدم يعدّل هذه الأعمدة فقط (لا يستطيع تغيير ID)
